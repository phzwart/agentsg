"""Write SellingClosure/Data.lean: the deposited operator table U as a Lean list.

Each element is (u1, u2, u3), the three columns of W: the new basis vectors in the
old basis, as in manuscript/benchmark/universal_operators_columns.json.
"""
import hashlib, json, pathlib
here = pathlib.Path(__file__).resolve().parent
src = here.parent / "benchmark" / "universal_operators_columns.json"
raw = open(src, "rb").read()
sha = hashlib.sha256(raw).hexdigest()
W = json.loads(raw)["W"]
def col(w, j):
    return "(%d, %d, %d)" % (w[0][j], w[1][j], w[2][j])
# Each operator is nine digits, entry + 3, columns first: (u1, u2, u3), each (x, y, z).
digits = "".join("".join(str(w[r][c] + 3) for c in range(3) for r in range(3)) for w in W)
assert all(0 <= w[r][c] + 3 <= 6 for w in W for r in range(3) for c in range(3))
lines = [digits[i:i + 90] for i in range(0, len(digits), 90)]
out = ["-- Generated by gen_data.py from manuscript/benchmark/universal_operators_columns.json.",
       "-- Do not edit by hand.  SHA-256 of the source JSON: " + sha,
       "-- (check_data.py recomputes the hash and regenerates this file to compare).",
       "", "namespace SellingClosure", "",
       "/-- SHA-256 of `universal_operators_columns.json`, from which `U` was generated. -/",
       'def sourceSHA256 : String := "%s"' % sha, "",
       "/-- Integer vectors in the basis (a, b, c) of the reduced superbase. -/",
       "abbrev V3 := Int × Int × Int", "",
       "/-- An operator, given by its three columns (the new a, b, c in the old basis). -/",
       "abbrev Op := V3 × V3 × V3", "",
       "/-- The table: for each operator nine digits, each entry plus 3, column by column. -/",
       "def Udigits : String :=",
       "  " + " ++\n  ".join('"%s"' % l for l in lines), "",
       "def decodeOp (d : List Nat) : Op :=",
       "  let e : Nat → Int := fun i => (d.getD i 0 : Int) - 3",
       "  ((e 0, e 1, e 2), (e 3, e 4, e 5), (e 6, e 7, e 8))", "",
       "def decodeAll : List Nat → List Op",
       "  | a :: b :: c :: d :: e :: f :: g :: h :: i :: rest =>",
       "      decodeOp [a, b, c, d, e, f, g, h, i] :: decodeAll rest",
       "  | _ => []", "",
       "/-- The deposited set 𝒰 of 6096 operators. -/",
       "def U : List Op := decodeAll (Udigits.toList.map fun ch => ch.toNat - '0'.toNat)", "",
       "end SellingClosure"]
(here / "SellingClosure" / "Data.lean").write_text("\n".join(out) + "\n")
print(len(W), "operators")
