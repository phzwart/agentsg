"""python -m sellingproofs {ledger,run,pin}

    ledger [--format md|tex|json] [--out FILE]   every claim: z-number, place, kind, statement
    run [z52 z60 ...] [--fast] [--strict-needs]   run the claims (all, or those z-numbers)
    pin                                           library version, data hashes, git commit
    tables [--out DIR]                            the SI's Table S12, as LaTeX fragments
"""
from __future__ import annotations

import argparse
import json
import re
import sys

from . import pin as _pin
from .registry import KINDS, NEEDS, load_all


def _tex(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"),
                 ("#", r"\#"), ("{", r"\{"), ("}", r"\}"), ("~", r"\~{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    return s


_ORDER = ["abstract", "§", "Table", "Fig.", "Appendix", "Lemma", "Proposition", "Definition", "Remark",
          "Data availability"]


def _place(w: str) -> tuple:
    """(document, kind, numbers, label) for one place in the paper, for sorting and grouping."""
    doc, _, rest = w.partition(" ")
    if doc not in ("main", "SI"):
        doc, rest = "main", w
    rest = rest.split(",")[0].strip()
    rest = re.sub(r"\([ivx]+\)(?:-\([ivx]+\))?$", "", rest)        # Proposition A10(iii) -> A10
    kind = next((k for k in _ORDER if rest.startswith(k)), "Lemma" if rest.startswith("Theorem") else rest)
    rank = _ORDER.index(kind) if kind in _ORDER else 99
    rank = min(rank, _ORDER.index("Lemma")) if kind in ("Lemma", "Proposition", "Definition", "Remark") else rank
    nums = tuple(int(x) for x in re.findall(r"\d+", rest))
    return (doc != "main", rank, nums, doc, rest)


def by_place(claims) -> list[tuple[str, str, list]]:
    """[(document, place, claims)] in the order of the paper."""
    groups = {}
    for c in claims:
        for w in c.where:
            k = _place(w)
            groups.setdefault(k, []).append(c)
    return [(k[3], k[4], v) for k, v in sorted(groups.items())]


def _tex_place(p: str) -> str:
    return _tex(p).replace("§", r"\S{}")


def ledger(fmt: str = "md") -> str:
    claims = load_all()
    if fmt == "tex-z":
        from .subjects import SUBJECTS
        rows = []
        for z in sorted({c.z for c in claims}):
            cs = [c for c in claims if c.z == z]
            kinds = ", ".join(sorted({c.kind for c in cs}))
            rows.append(f"{z} & {_tex(SUBJECTS.get(z, ''))} & {kinds} & {len(cs)} \\\\")
        return "\n".join(rows)
    if fmt == "tex-places":
        rows = []
        for doc, place, cs in by_place(claims):
            zs = sorted({c.z for c in cs})
            rows.append(f"{'' if doc == 'main' else 'SI '}{_tex_place(place)} & {', '.join(zs)} & {len(cs)} \\\\")
        return "\n".join(rows)
    if fmt == "json":
        return json.dumps([c.__dict__ for c in claims], indent=1, ensure_ascii=False)
    if fmt == "tex":
        rows = []
        for z in sorted({c.z for c in claims}):
            cs = [c for c in claims if c.z == z]
            where = "; ".join(sorted({w for c in cs for w in c.where}))
            kinds = ", ".join(sorted({c.kind for c in cs}))
            needs = ", ".join(sorted({n for c in cs for n in c.needs}))
            rows.append(f"{z} & {_tex(where)} & {kinds}{' (' + needs + ')' if needs else ''} & {len(cs)} \\\\")
        return "\n".join(rows)
    out = ["# Ledger of claims", "",
           f"{len(claims)} checks of {len({c.z for c in claims})} numbered statements.", "",
           "| z | where | kind | needs | statement | check |", "|---|---|---|---|---|---|"]
    for c in claims:
        out.append(f"| {c.z} | {'; '.join(c.where)} | {c.kind} | {', '.join(c.needs)} | "
                   f"{c.statement.replace('|', '/')} | `{c.function.split('.')[-1]}` |")
    out += ["", "Kinds: " + "; ".join(f"**{k}** {v}" for k, v in KINDS.items()) + ".",
            "", "Needs: " + "; ".join(f"**{k}** {v}" for k, v in NEEDS.items()) + "."]
    return "\n".join(out)


def tables(out) -> int:
    """write the supporting information's Table S12 parts: the checks by place in the main
    text and in the supporting information, and the subjects of the z-numbers."""
    from pathlib import Path

    from .subjects import SUBJECTS
    out = Path(out)
    claims = load_all()
    head = "% generated by python -m sellingproofs tables; do not edit\n"
    for doc, name in (("main", "checks_main.tex"), ("SI", "checks_si.tex")):
        rows = [f"{_tex_place(place)} & {', '.join(sorted({c.z for c in cs}))} & {len(cs)} \\\\"
                for d, place, cs in by_place(claims) if d == doc]
        (out / name).write_text(head + "\n".join(rows) + "\n")
    items = []
    for z in sorted({c.z for c in claims}):
        n = sum(c.z == z for c in claims)
        items.append(f"{z}: {_tex(SUBJECTS.get(z, ''))} ({n})")
    (out / "checks_subjects.tex").write_text(head + "; ".join(items) + ".\n")
    from .claims.test_z62_formal_proofs import TEX, THEOREMS
    rows = []
    for name, where, statement, native in THEOREMS:
        w = "; ".join(_tex_place(x.split(" ", 1)[1]) if x.startswith("main ") else _tex_place(x) for x in where)
        ev = ", ".join(r"\texttt{" + _tex(n).replace(r"\_", r"\_\allowbreak ") + "}" for n in sorted(native)) or "none"
        rows.append(r"\texttt{" + _tex(name).replace(".", r".\allowbreak ").replace(r"\_", r"\_\allowbreak ") + "} & " + w + " & "
                    + TEX[name] + " & " + ev + r" \\")
    (out / "checks_lean.tex").write_text(head + "\n".join(rows) + "\n")
    print(f"{len(claims)} checks written to {out}")
    return 0


def run(zs, fast=False, strict=False, extra=()) -> int:
    import pytest
    from . import paths
    ini = paths.SUPPLEMENT / "pytest.ini"
    args = [str(paths.PACKAGE / "claims"), "--rootdir", str(paths.SUPPLEMENT)]
    args += ["-c", str(ini)] if ini.is_file() else ["-p", "no:cacheprovider", "-q"]
    if zs:
        args += ["-m", " or ".join(zs)]
    if fast:
        args.append("--fast")
    if strict:
        args.append("--strict-needs")
    return pytest.main(args + list(extra))


def show_pin() -> int:
    head, clean = _pin.git_state()
    ok = True
    print(f"repository  {_pin.REPOSITORY}")
    print(f"commit      {head}{'' if clean else ' (uncommitted changes)'}")
    v = _pin.agentsg_version()
    print(f"agentsg     {v} (pinned {_pin.AGENTSG_VERSION})")
    ok &= v == _pin.AGENTSG_VERSION
    for rel, want in _pin.SHA256.items():
        got = _pin.sha256(rel)
        print(f"{'ok' if got == want else 'MISMATCH':8s}    {rel}")
        ok &= got == want
    return 0 if ok else 1


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="python -m sellingproofs", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    l = sub.add_parser("ledger"); l.add_argument("--format", default="md", choices=("md", "tex", "tex-z", "tex-places", "json"))
    l.add_argument("--out")
    sub.add_parser("run", help="run [z52 ...] [--fast] [--strict-needs] [pytest options]")
    sub.add_parser("pin")
    t = sub.add_parser("tables"); t.add_argument("--out", default=".")
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv[:1] == ["run"]:
        rest = argv[1:]
        zs = [x for x in rest if re.fullmatch(r"z\d\d", x)]
        opts = [x for x in rest if x not in zs and x not in ("--fast", "--strict-needs")]
        return run(zs, "--fast" in rest, "--strict-needs" in rest, opts)
    a = p.parse_args(argv)
    if a.cmd == "ledger":
        txt = ledger(a.format)
        if a.out:
            open(a.out, "w").write(txt + "\n")
        else:
            print(txt)
        return 0
    if a.cmd == "tables":
        return tables(a.out)
    return show_pin()


if __name__ == "__main__":
    sys.exit(main())
